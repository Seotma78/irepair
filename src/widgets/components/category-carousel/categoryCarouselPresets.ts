export function applyPreset(current: CategoryCarouselConfig, presetId: string): CategoryCarouselConfig {
  const preset = CATEGORY_CAROUSEL_PRESETS.find((p) => p.id === presetId);
  if (!preset) return current;
  return {
    ...current,
    ...preset.patch,
    activePreset: presetId,
  };
}
